import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const pkg = JSON.parse(read('package.json'));

test('build output is generated by CI and never committed', () => {
  const ignored = read('.gitignore')
    .split(/\r?\n/)
    .map((line) => line.trim());
  assert.ok(ignored.includes('dist/'), 'dist/ must stay in .gitignore');
  assert.ok(ignored.includes('_site/'), 'the staged Pages site must stay in .gitignore');
});

test('the Pages workflow publishes the exact path the production loader requests', () => {
  const loader = read('loader.user.js');
  const base = /const base = '([^']+)'/.exec(loader)?.[1];
  assert.ok(base, 'loader declares its base URL');
  const { pathname } = new URL(base);
  const sitePath = pathname.replace(/^\/BC-Responsive\//, '');
  const workflow = read('.github/workflows/static.yml');
  assert.ok(sitePath.endsWith('/main.js'), sitePath);
  assert.ok(
    workflow.includes(`_site/${sitePath.replace(/\/main\.js$/, '')}`),
    'static.yml must stage dist/ under the loader URL path, or installed loaders break',
  );
  assert.ok(workflow.includes('npm test') && workflow.includes('npm run build'));
  assert.ok(workflow.includes('loader.user.js'), 'the loader is published so @updateURL works');
  assert.ok(loader.includes('@updateURL https://awdrrawd.github.io/BC-Responsive/loader.user.js'));
});

test('README heading shows the package version', () => {
  assert.equal(read('README.md').split(/\r?\n/)[0], `# Responsive_Liko ${pkg.version}`);
});

test('dependency licenses ship with the repo and are published with the site', () => {
  for (const file of ['licenses/ModSDK-MIT.txt', 'licenses/LZString-MIT.txt'])
    assert.match(read(file), /^MIT License/, file);
  assert.ok(read('.github/workflows/static.yml').includes('_site/licenses'));
});

test('automation files referenced by the docs exist', () => {
  for (const file of [
    '.github/workflows/checks.yml',
    '.github/workflows/static.yml',
    '.github/dependabot.yml',
    'scripts/bundle-size.mjs',
  ])
    assert.ok(existsSync(new URL(`../${file}`, import.meta.url)), file);
});
